"""Cumulus over the thermals that carry one: instanced objects with a particle emitter.

`engine/clouds.py` decides which thermals carry a cloud and how fast each emitter should
run; this turns that into instances of the object in `xp_gliding/assets/clouds/`,
generated by `tools/make_cloud_objs.py`. What X-Plane does with those particles, and what
it costs, is in docs/phase2.md.

Never per frame. `update` runs a few times a second while tiles are loading, once a second
after that, and only sets positions when a cloud is created or its rate changes: instances
follow X-Plane's local origin by themselves (`instanceSetAutoShift`).

The height is the base of the clouds, above the ground under the glider when each cloud is
created: an emitted particle stays where it is, so a cloud cannot follow the terrain (nor
should it, real cloud bases are level). It is the top of the engine's lift, which uses the
glider's own AGL for the moment (no terrain under each thermal yet).

Nothing here imports `xp`: the SDK calls are in `xpio.SkyObjects`.
"""

import math
import time

from ..engine.clouds import CREATE, DESTROY, RATE, CloudCatalog, CloudPlanner, cloud_scale

OBJECT = "cumulus"
PLAN_PERIOD_S = 5.0  # choosing the clouds, once the sky is complete
FILLING_PLAN_PERIOD_S = 1.0  # and while it fills, or while new clouds are waiting their turn
JUMP_S = 120.0  # a larger jump of the sim's clock than this: time was changed, start over


class CloudStatus:
    """Published as datarefs."""

    __slots__ = ("count", "created", "destroyed", "rate_changes", "tiles_missing", "update_us",
                 "update_us_max", "plan_us", "nearest_m", "rate_dummy", "scale_dummy")

    def __init__(self):
        self.count = self.created = self.destroyed = self.rate_changes = 0
        self.tiles_missing = 0
        self.update_us = self.update_us_max = self.plan_us = 0.0
        self.nearest_m = -1.0  # the nearest drawn cloud, for tools
        # The object's emitter reads these names, which are per instance. They exist so the
        # object finds them when it loads; their own value is never used.
        self.rate_dummy = self.scale_dummy = 0.0


class CumulusClouds:
    def __init__(self, sky, log=print, params=None):
        self.sky = sky
        self.log = log
        self.planner = CloudPlanner(params)
        self.status = CloudStatus()
        self.catalog = None
        self.config = None  # the field's config the catalog was made for
        self.frame = None
        self.instances = {}  # Thermal -> (instance, base height m MSL)
        self.obj = None
        self._loading = False
        self.failed = False
        self.closed = False
        self._next_plan = 0.0
        self._last_t = None
        self.more = False  # the planner left new clouds for later

    # --- the object ---------------------------------------------------------------

    def _ready(self):
        if self.obj is None and not self._loading and not self.failed:
            self._loading = True
            self.sky.load_async(OBJECT, self._loaded)
        return self.obj is not None

    def _loaded(self, obj, name):
        self._loading = False
        if obj is None:
            self.failed = True
            self.log(f"could not load the cloud object {name}; clouds off")
        elif self.closed:
            self.sky.unload(obj)
        else:
            self.obj = obj

    # --- a few times a second ---------------------------------------------------------

    def update(self, field, frame, s, msl_m, zi, now):
        """Bring the clouds up to date for the aircraft state s, at msl_m metres MSL."""
        self.closed = False
        if self.failed or not self._ready():
            return
        t0 = time.perf_counter()
        t = s.sky_t_s
        st = self.status
        if self.config is not field.config or (self._last_t is not None
                                               and abs(t - self._last_t) > JUMP_S):
            self.clear()
            self.config = field.config
            self.catalog = CloudCatalog(field.config, frame, self.planner.params, field.accept)
            self.frame = frame
        elif frame is not self.frame:
            self.catalog.set_frame(frame)
            self.frame = frame
        self._last_t = t
        # Planning and loading tiles are each close to a frame's budget: never both at once.
        if self.catalog.started and now >= self._next_plan:
            e, n = frame.to_enu(s.lat, s.lon)
            self._apply(self.planner.step(self.catalog.thermals(), e, n, t), msl_m - s.agl_m, zi)
            self.more = self.planner.more_waiting
            soon = self.catalog.missing or self.more
            wait = FILLING_PLAN_PERIOD_S if soon else PLAN_PERIOD_S
            self._next_plan = now + min(wait, self.planner.next_change - t)
            st.nearest_m = min((math.hypot(th.e - e, th.n - n) for th in self.instances), default=-1.0)
            st.plan_us = (time.perf_counter() - t0) * 1e6
        else:
            self.catalog.update(t, s.lat, s.lon)
            st.tiles_missing = self.catalog.missing
        st.count = len(self.instances)
        st.update_us = (time.perf_counter() - t0) * 1e6
        st.update_us_max = max(st.update_us_max, st.update_us)

    def _set(self, instance, th, base_m, rate):
        x, y, z = self.sky.world_to_local(th.lat, th.lon, base_m)
        self.sky.set_position(instance, x, y, z, (rate, cloud_scale(th)))

    def _apply(self, actions, ground_m, zi):
        st = self.status
        for action, th, rate in actions:
            if action == CREATE:
                instance = self.sky.create(self.obj, ("xp_gliding/clouds/rate", "xp_gliding/clouds/scale"))
                base_m = ground_m + self.config.sky.cloud_base_zzi * zi
                self.instances[th] = (instance, base_m)
                self._set(instance, th, base_m, rate)
                self.sky.auto_shift(instance)
                st.created += 1
            elif action == RATE:
                instance, base_m = self.instances[th]
                self._set(instance, th, base_m, rate)
                st.rate_changes += 1
            elif action == DESTROY:
                instance, _ = self.instances.pop(th)
                self.sky.destroy(instance)
                st.destroyed += 1

    # --- off --------------------------------------------------------------------

    def clear(self):
        """Destroy every instance: their particles go at once. The object stays loaded."""
        for instance, _ in self.instances.values():
            self.sky.destroy(instance)
        self.instances.clear()
        self.planner.clear()
        self.status.count = 0
        self.status.nearest_m = -1.0
        self._next_plan = 0.0

    def shutdown(self):
        """The plugin is being disabled: nothing of ours stays in X-Plane."""
        self.closed = True
        self.clear()
        self.catalog = self.config = self.frame = None
        self._last_t = None
        if self.obj is not None:
            self.sky.unload(self.obj)
            self.obj = None
