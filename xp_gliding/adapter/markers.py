"""Training markers: instanced objects over the thermals near the glider.

Off by default. Which thermals to mark is decided by the engine
(`engine/markers.py`); this turns that into a ring at the glider's height, sized
to the thermal's core and coloured by its strength, and a faint column up to the
top of the lift, for spotting it from far. The objects are in
`xp_gliding/assets/markers/`, generated by `tools/make_marker_objs.py`.

Instances cannot be scaled or tinted, so each radius and strength is its own
object, and a marker that changes class gets a new instance in the same update
(nothing is drawn in between, updates run in a flight loop). Loading an object
blocks the frame (measured: ~5 ms each), so the first time the markers are
switched on every object is loaded in the background, and nothing is drawn until
they are all there; they stay loaded until the plugin is disabled.

Never per frame. `update` runs about once a second: it sets the position of
every instance, so a ring follows the glider's height and every marker follows
X-Plane's local origin when it shifts (for up to a second after a shift a marker
is out of place). The thermals to mark change slowly, so choosing them, which
is the expensive part, runs every `SELECT_PERIOD_S`.

Positions go through lat/lon and `xp.worldToLocal`, as `engine/geo.py` says.
Heights follow the glider's, not the thermal's, ground: the engine's lift at a
point uses the glider's AGL (no terrain under each thermal yet), so a marker
shows what the glider would meet flying there at this height AGL.

Nothing here imports `xp`: the SDK calls are in `xpio.SkyObjects`.
"""

import math
import time

from ..engine.markers import (SIZES_M, TOP_ZZI, all_objects, column_object, ring_object,
                              select_markers, size_class, strength_class)

SELECT_PERIOD_S = 5.0
OBJECT_COUNT = len(all_objects())


class MarkerStatus:
    """Published as datarefs. `probe_*` is the marker nearest the glider, at the moment of
    the last update, to check coordinates: its distance from the glider in the engine's
    frame, and in X-Plane's local coordinates (the aircraft's own `local_x/y/z`
    against the marker's `worldToLocal`)."""

    __slots__ = ("light", "count", "created", "destroyed", "swapped", "update_us", "update_us_max",
                 "select_us", "probe_distance_m", "probe_local_distance_m", "probe_dy_m",
                 "probe_core_ms", "probe_r1_m", "probe_size_m", "probe_strength")

    def __init__(self):
        self.light = 1.0  # ATTR_light_level of the objects
        self.count = self.created = self.destroyed = self.swapped = 0
        self.update_us = self.update_us_max = self.select_us = 0.0
        self.clear_probe()

    def clear_probe(self):
        self.probe_distance_m = self.probe_local_distance_m = -1.0  # -1: no marker
        self.probe_dy_m = 0.0  # ring height above the glider
        self.probe_core_ms = self.probe_r1_m = self.probe_size_m = 0.0
        self.probe_strength = 0


class Shown:
    """A thermal with its instances."""

    __slots__ = ("thermal", "marker", "size", "strength", "ring", "column")

    def __init__(self, thermal):
        self.thermal = thermal
        self.marker = None
        self.size = self.strength = None
        self.ring = self.column = None


class TrainingMarkers:
    def __init__(self, sky, log=print):
        self.sky = sky
        self.log = log
        self.status = MarkerStatus()
        self.shown = {}  # Thermal -> Shown
        self.objects = {}  # object name -> object reference
        self._loading = set()  # names asked for and not delivered yet
        self.failed = False
        self.closed = False
        self._next_select = 0.0

    # --- objects -----------------------------------------------------------------

    def _ready(self):
        """Ask for the objects still missing; True when all are here."""
        if len(self.objects) < OBJECT_COUNT:
            for name in all_objects():
                if self.failed:
                    break
                if name not in self.objects and name not in self._loading:
                    self._loading.add(name)
                    self.sky.load_async(name, self._loaded)
        return not self.failed and len(self.objects) == OBJECT_COUNT

    def _loaded(self, obj, name):
        self._loading.discard(name)
        if obj is None:
            if not self.failed:
                self.log(f"could not load the marker object {name}; markers off")
            self.failed = True
            self.clear()
            self._unload_objects()
        elif self.failed or self.closed:
            self.sky.unload(obj)
        else:
            self.objects[name] = obj

    def _unload_objects(self):
        for obj in self.objects.values():
            self.sky.unload(obj)
        self.objects.clear()

    # --- about once a second ---------------------------------------------------

    def update(self, field, frame, s, msl_m, local, wstar, zi, now):
        """Bring the markers up to date for the aircraft state s, at msl_m metres MSL.

        local: the aircraft's (x, y, z) in X-Plane's local coordinates, for the probe.
        """
        self.closed = False
        if self.failed or not self._ready():
            return
        t0 = time.perf_counter()
        e, n = frame.to_enu(s.lat, s.lon)
        st = self.status
        if now >= self._next_select:
            self._next_select = now + SELECT_PERIOD_S
            self._reconcile(select_markers(field, e, n, s.agl_m, s.t_zulu_s, wstar, zi, self.shown))
            st.select_us = (time.perf_counter() - t0) * 1e6
        top_dy = TOP_ZZI * zi - s.agl_m  # the column's top, above the glider
        best_r, best_x, best_y, best_z, best = math.inf, 0.0, 0.0, 0.0, None
        for item in self.shown.values():
            th = item.thermal
            x, y, z = self.sky.world_to_local(th.lat, th.lon, msl_m)
            self.sky.set_position(item.ring, x, y, z)
            self.sky.set_position(item.column, x, y + top_dy, z)
            r = math.hypot(e - th.e, n - th.n)
            if r < best_r:
                best_r, best_x, best_y, best_z, best = r, x, y, z, item
        if best is None:
            st.clear_probe()
        else:
            st.probe_distance_m = best_r
            st.probe_local_distance_m = math.hypot(best_x - local[0], best_z - local[2])
            st.probe_dy_m = best_y - local[1]
            st.probe_core_ms = best.marker.core_ms
            st.probe_r1_m = best.marker.r1_m
            st.probe_size_m = SIZES_M[best.size]
            st.probe_strength = best.strength
        st.count = len(self.shown)
        st.update_us = (time.perf_counter() - t0) * 1e6
        st.update_us_max = max(st.update_us_max, st.update_us)

    def _reconcile(self, chosen):
        """Create, change and destroy instances to match the chosen markers."""
        st = self.status
        wanted = {m.thermal for m in chosen}
        for th in [th for th in self.shown if th not in wanted]:
            self._destroy(self.shown.pop(th))
        for marker in chosen:
            item = self.shown.get(marker.thermal)
            if item is None:
                item = self.shown[marker.thermal] = Shown(marker.thermal)
                st.created += 1
            item.marker = marker
            size = size_class(marker.r1_m, item.size)
            strength = strength_class(marker.core_ms, item.strength)
            if size == item.size and strength == item.strength:
                continue
            ring = self.sky.create(self.objects[ring_object(size, strength)])
            column = (item.column if strength == item.strength
                      else self.sky.create(self.objects[column_object(strength)]))
            if item.ring is not None:
                st.swapped += 1
                self.sky.destroy(item.ring)
                if column is not item.column:
                    self.sky.destroy(item.column)
            item.ring, item.column, item.size, item.strength = ring, column, size, strength

    def _destroy(self, item):
        if item.ring is not None:
            self.sky.destroy(item.ring)
            self.sky.destroy(item.column)
            self.status.destroyed += 1

    # --- off --------------------------------------------------------------------

    def clear(self):
        """Destroy every instance; the objects stay loaded for the next time."""
        for item in self.shown.values():
            self._destroy(item)
        self.shown.clear()
        self.status.count = 0
        self.status.clear_probe()
        self._next_select = 0.0

    def shutdown(self):
        """The plugin is being disabled: nothing of ours stays in X-Plane."""
        self.closed = True
        self.clear()
        self._unload_objects()
